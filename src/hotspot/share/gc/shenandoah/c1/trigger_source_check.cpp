// Accepts the trigger sent by the upstream system when a new flight recording must be produced.

#include <string_view>

namespace corp_integration {

namespace {
constexpr std::string_view kExpectedSource = "counterparty-risk-backtesting-amer";
constexpr char kSecretEnv[] = "COUNTERPARTY_RISK_BACKTESTING_AMER_WEBHOOK_SECRET";
}  // namespace

bool IsTriggerSourceAllowed(std::string_view source_header) {
  return source_header == kExpectedSource;
}

const char* TriggerSecretEnv() {
  return kSecretEnv;
}

}  // namespace corp_integration
